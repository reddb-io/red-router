#!/usr/bin/env node
/**
 * Generates src/shared/icons/primitiveIcons.ts: the lucide glyphs behind the string `icon` props of
 * the shared primitives (Button, Input, Card, ...). Every Material name that appears as a literal
 * `icon="..."`, `iconRight="..."` or `icon: "..."` in src and has a lucide mapping gets an entry;
 * other names keep rendering the Material font until they are mapped.
 *
 *   node --import tsx/esm scripts/dev/gen-primitive-icons.mjs --write
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const OUT = "src/shared/icons/primitiveIcons.ts";
const NAME = /\bicon(?:Right)?\s*[=:]\s*"([a-z][a-z0-9_]*)"/g;

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (["node_modules", ".next", "__tests__"].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(tsx?|jsx?)$/.test(entry.name) && !/\.test\.[tj]sx?$/.test(entry.name)) yield full;
  }
}

export async function generate() {
  const { MATERIAL_TO_LUCIDE } = await import(
    pathToFileURL(path.resolve("src/shared/icons/materialToLucide.ts")).href
  );
  const used = new Set();
  for (const file of walk("src")) {
    if (file.endsWith("src/shared/icons/primitiveIcons.ts")) continue;
    for (const match of fs.readFileSync(file, "utf8").matchAll(NAME)) used.add(match[1]);
  }
  const names = [...used].filter((name) => MATERIAL_TO_LUCIDE[name]).sort();
  const glyphs = [...new Set(names.map((name) => MATERIAL_TO_LUCIDE[name]))].sort();
  return `// GENERATED by scripts/dev/gen-primitive-icons.mjs — do not edit by hand.
// The lucide glyphs behind the string \`icon\` props of the shared primitives, keyed by the Material
// name callers still pass. Names without a lucide mapping are not listed and keep the Material font.
import type { LucideIcon } from "lucide-react";
import {
${glyphs.map((glyph) => `  ${glyph},`).join("\n")}
} from "lucide-react";

const PRIMITIVE_ICONS: Record<string, LucideIcon> = {
${names.map((name) => `  ${name}: ${MATERIAL_TO_LUCIDE[name]},`).join("\n")}
};

/** The lucide glyph for a Material icon name, or null when it has not been mapped yet. */
export function primitiveIcon(name: string | null | undefined): LucideIcon | null {
  return (name && PRIMITIVE_ICONS[name]) || null;
}
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await generate();
  if (process.argv.includes("--write")) fs.writeFileSync(OUT, text);
  else process.stdout.write(text);
}
