/**
 * Resolves a glyph for the shell: a lucide export name directly, else a legacy Material Symbols
 * name through `MATERIAL_TO_LUCIDE`, else a neutral `Circle`.
 */
export function navIcon(nameOrMaterial: string): IconGlyph {
  if (Object.prototype.hasOwnProperty.call(NAV_ICONS, nameOrMaterial)) {
    return NAV_ICONS[nameOrMaterial];
  }
  const lucideName = lucideForMaterial(nameOrMaterial);
  if (lucideName && Object.prototype.hasOwnProperty.call(NAV_ICONS, lucideName)) {
    return NAV_ICONS[lucideName];
  }
  return Circle;
}
